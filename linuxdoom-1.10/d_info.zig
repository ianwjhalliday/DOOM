/// The sprite names for R_InitSprites. R_InitSpriteDefs counts them by
/// scanning for a null entry, but vanilla's array had none and the scan read
/// past its end. The null sentinel here stops it. This array goes away once
/// r_things is Zig and reads @typeInfo(SpriteNum).@"enum".field_names.
pub const sprnames: [SpriteNum.count:null]?[*:0]const u8 = blk: {
    const field_names = @typeInfo(SpriteNum).@"enum".field_names;
    const field_values = @typeInfo(SpriteNum).@"enum".field_values;
    var result: [SpriteNum.count:null]?[*:0]const u8 = undefined;

    for (field_names, field_values) |name, i| {
        result[i] = name.ptr;
    }

    break :blk result;
};

fn mobjAction(f: *const fn (*MObj) callconv(.c) void) ActionFn {
    return .{ .acp1 = p_tick.thinkFn(MObj, f) };
}

fn pspAction(f: *const fn (*Player, *PspDef) callconv(.c) void) ActionFn {
    return .{ .acp2 = @ptrCast(f) };
}

/// Picks the ActionFn member the way vanilla's table initializers did.
/// A null action sets acp1, which is the member C's {NULL} initializes.
fn action(comptime f: anytype) ActionFn {
    if (@TypeOf(f) == @TypeOf(null)) return .{ .acp1 = null };
    return switch (@typeInfo(@typeInfo(@TypeOf(f)).pointer.child).@"fn".param_types.len) {
        1 => mobjAction(f),
        2 => pspAction(f),
        else => @compileError("not a state action"),
    };
}

fn s(sprite: SpriteNum, frame: c_long, tics: c_long, comptime act: anytype, nextstate: StateNum, misc1: c_long, misc2: c_long) State {
    return .{
        .sprite = sprite,
        .frame = frame,
        .tics = tics,
        .action = action(act),
        .nextstate = nextstate,
        .misc1 = misc1,
        .misc2 = misc2,
    };
}

